#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md and App/Resources/Credits.rtf.

    make_notices.py <rust-notices.md>

The Rust part comes from `cargo about` (see `make notices`); the C/C++ libraries are added here
from their vendored licence files.
"""

import glob
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = Path(os.path.expanduser("~/.cargo/registry/src"))


def registry_file(pattern):
    matches = sorted(glob.glob(str(REGISTRY / "*" / pattern)))
    if not matches:
        sys.exit(f"missing {pattern}: run `cargo fetch` in core/")
    return Path(matches[-1])


JPEGLI = ROOT / "core" / "vendor" / "jpegli"
NATIVE = [
    ("jpegli", "BSD-3-Clause", "JPEG encoder (google/jpegli)", JPEGLI / "LICENSE"),
    ("Highway", "Apache-2.0 OR BSD-3-Clause", "SIMD library used by jpegli",
     JPEGLI / "third_party" / "highway" / "LICENSE"),
    ("libjpeg-turbo headers", "IJG AND BSD-3-Clause AND Zlib", "jpeglib.h API definitions used by jpegli",
     JPEGLI / "third_party" / "libjpeg-turbo" / "LICENSE.md"),
    ("libwebp", "BSD-3-Clause", "WebP encoder, via libwebp-sys", registry_file("libwebp-sys-*/vendor/COPYING")),
    ("libdeflate", "MIT", "DEFLATE compressor used by oxipng, via libdeflater",
     registry_file("libdeflate-sys-*/libdeflate/COPYING")),
]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rust = Path(sys.argv[1]).read_text()

    parts = [
        "# Third-party notices\n",
        "Krimp is licensed under GPL-3.0-or-later (see `LICENSE`). It statically links the libraries",
        "below; their licences and copyright notices follow.\n",
        "<!-- Generated by `make notices` (scripts/make_notices.py). Do not edit by hand. -->\n",
        "## C/C++ libraries\n",
    ]
    for name, spdx, what, path in NATIVE:
        parts += [f"### {name}\n", f"{what}. Licence: {spdx}.\n", "```", path.read_text().strip(), "```\n"]
    parts += ["## Rust crates\n", rust.strip(), ""]
    notices = "\n".join(parts)
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text(notices)

    (ROOT / "App" / "Resources").mkdir(parents=True, exist_ok=True)
    (ROOT / "App" / "Resources" / "Credits.rtf").write_text(to_rtf(notices))


def to_rtf(text):
    """Plain-text RTF in a small monospaced font; headings in bold."""
    def escape(line):
        out = []
        for ch in line:
            if ch in "\\{}":
                out.append("\\" + ch)
            elif ord(ch) > 127:
                code = ord(ch)
                if code > 0xFFFF:  # outside the BMP: emit a surrogate pair
                    code -= 0x10000
                    out.append(f"\\u{0xD800 + (code >> 10) - 65536}?\\u{0xDC00 + (code & 0x3FF) - 65536}?")
                else:
                    out.append(f"\\u{code if code < 32768 else code - 65536}?")
            else:
                out.append(ch)
        return "".join(out)

    lines = []
    for line in text.splitlines():
        if line.startswith("<!--") or line.startswith("```"):
            continue
        if line.startswith("#"):
            lines.append("\\b " + escape(line.lstrip("#").strip()) + "\\b0")
        else:
            lines.append(escape(line))
    body = "\\\n".join(lines)
    return "{\\rtf1\\ansi\\ansicpg1252\\deff0{\\fonttbl{\\f0\\fmodern Menlo;}}\\f0\\fs18\n" + body + "\n}\n"


if __name__ == "__main__":
    main()
